"""Contratos de acesso a dados e transações exigidos pelos casos de uso."""

from contextlib import AbstractContextManager
from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class LivrosPort(Protocol):
    def todos(self) -> tuple[dict, ...]: ...
    def obter(self, livro_id: str) -> dict: ...
    def por_codigo(self, codigo: str) -> dict: ...
    def buscar_por_titulo(self, titulo: str) -> list[dict]: ...
    def buscar_por_autor(self, autor: str) -> list[dict]: ...
    def filtrar_por_genero(self, genero: str) -> list[dict]: ...
    def consultar_estoque(self, titulo: str) -> int: ...
    def listar_lancamentos(self) -> list[dict]: ...


@runtime_checkable
class EstadoPort(Protocol):
    def obter(self, colecao: str, identificador: str, padrao: Any = None) -> Any: ...
    def salvar(self, colecao: str, identificador: str, valor: Any) -> None: ...
    def listar(self, colecao: str) -> tuple: ...
    def obter_ou_criar(self, colecao: str, identificador: str, padrao: Any) -> Any: ...
    def fila(self) -> list[str]: ...
    def configurar_loja(self, horario: str, lotacao: int) -> None: ...
    def informacoes_loja(self) -> dict: ...
    def obter_avaliacao(self, livro_id: str, cliente_id: str) -> dict | None: ...
    def salvar_avaliacao(self, livro_id: str, cliente_id: str, avaliacao: dict) -> None: ...
    def listar_avaliacoes(self, livro_id: str) -> list[dict]: ...


@runtime_checkable
class TransacaoPort(Protocol):
    def iniciar(self) -> AbstractContextManager: ...
